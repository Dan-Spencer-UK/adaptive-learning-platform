/**
 * CC-05D: mechanical governance/QA gate for instructional-visual semantic
 * contracts. Independently recomputes every count from the live CC-05A
 * corpus and the live CC-05D contract/canonical-variant data -- never
 * trusts a record's own claims, the same discipline
 * scripts/content/validate-pedagogy.ts already uses.
 *
 * Design authority: docs/architecture/CC-05D-INSTRUCTIONAL-VISUAL-
 * GOVERNANCE-AND-SEMANTIC-QA.md §E.
 *
 * Usage:
 *   node scripts/visual-governance/check-visual-governance.ts            (report)
 *   node scripts/visual-governance/check-visual-governance.ts --check     (exit 1 on any failure)
 */

